import {chromium} from 'playwright';import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 let response=await page.goto('http://127.0.0.1:33231/esi-services.html',{waitUntil:'load'});
 assert.equal(response?.status(),200);await page.getByRole('heading',{name:/The full ESI service catalog/}).waitFor();
 assert.equal(await page.locator('article.es-card').count(),22);
 assert.ok(await page.getByText('Carbon Credits & Offset Integrity').count()>=1);
 await page.getByRole('button',{name:'Finance & Incentives'}).click();
 assert.equal(await page.locator('article.es-card').count(),3);
 await page.getByRole('button',{name:'All',exact:true}).click();
 await page.locator('#es-search').fill('EPD');
 assert.ok(await page.locator('article.es-card').count()>=1);
 await page.locator('#es-search').fill('zzz-no-matches');
 assert.equal(await page.locator('article.es-card').count(),0);
 await page.locator('#es-search').fill('');
 assert.equal(await page.locator('article.es-card').count(),22);
 await page.locator('article.es-card').first().locator('summary').click();
 assert.ok(await page.locator('article.es-card').first().getByText('Professional boundaries').isVisible());
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+3),false,'Catalog mobile overflow');
 response=await page.goto('http://127.0.0.1:33231/esi-financial-lab.html',{waitUntil:'load'});
 assert.equal(response?.status(),200);await page.getByRole('heading',{name:/Turn carbon exposure/}).waitFor();
 assert.equal(await page.locator('#cf-gross').innerText(),'$494,000');
 assert.equal(await page.locator('#cf-net').innerText(),'$400,400');
 assert.equal(await page.locator('#cf-avoided').innerText(),'$93,600');
 assert.match(await page.locator('#cf-cost').innerText(),/100,000/);
 await page.locator('#cf-price').fill('100');
 assert.equal(await page.locator('#cf-gross').innerText(),'$760,000');
 await page.locator('#cf-emissions').fill('0');
 assert.equal(await page.locator('#cf-gross').innerText(),'$0');
 assert.equal(await page.locator('#cf-net').innerText(),'$0');
 await page.getByRole('tab',{name:/Offset integrity/}).click();
 assert.equal(await page.locator('#cf-offset-status').innerText(),'UNCERTAIN');
 for(const box of await page.locator('#cf-offset-checks input').all()) await box.check();
 assert.match(await page.locator('#cf-offset-count').innerText(),/6 \/ 6/);
 assert.equal(await page.locator('#cf-offset-status').innerText(),'UNCERTAIN','Not auto-certifying offsets');
 await page.getByRole('tab',{name:/Incentive evidence/}).click();
 for(const box of await page.locator('#cf-incentive-checks input').all()) await box.check();
 assert.match(await page.locator('#cf-incentive-count').innerText(),/6 of 6/);
 const note=await page.locator('.cf-warning').innerText();
 assert.match(note,/not a carbon-tax bill/i);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+3),false,'Financial lab mobile overflow');
 assert.deepEqual(errors,[],'No uncaught browser JS errors');
 console.log('ESI catalog 22 offers + financial/offset/incentive interactive mobile browser tests PASS');
}finally {await browser.close()}
